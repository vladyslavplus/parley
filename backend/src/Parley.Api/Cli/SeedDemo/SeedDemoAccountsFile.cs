using System.Text;
using Parley.Identity.Contracts.DemoSeed;

namespace Parley.Api.Cli.SeedDemo;

/// <summary>Writes the generated demo passwords to a private file. Nothing else writes or logs them.</summary>
public static class SeedDemoAccountsFile
{
    private const string TemporarySuffix = ".tmp";

    private const string ProbeSuffix = ".probe";

    private const string NoTeam = "-";

    /// <summary>Read and write for the owner only.</summary>
    private const UnixFileMode OwnerOnly = UnixFileMode.UserRead | UnixFileMode.UserWrite;

    /// <summary>Creates the directory of the accounts file, so a missing folder fails before any account exists.</summary>
    private static void EnsureDirectory(string path)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(path);
        var directory = Path.GetDirectoryName(Path.GetFullPath(path));
        if (!string.IsNullOrEmpty(directory))
        {
            Directory.CreateDirectory(directory);
        }
    }

    /// <summary>
    /// Proves the accounts file can be written before any account is created: creates the directory and writes and removes
    /// a probe file next to the target. Throws <see cref="IOException"/> or <see cref="UnauthorizedAccessException"/> when not.
    /// </summary>
    public static void VerifyWritable(string path)
    {
        EnsureDirectory(path);
        var probe = path + ProbeSuffix;
        WritePrivate(probe, string.Empty);
        File.Delete(probe);
    }

    /// <summary>
    /// Writes the text with owner-only permissions where the platform has file modes (Unix). The mode is set when the file
    /// is created, so no other user can read it in between. On Windows the default ACL of the folder applies.
    /// </summary>
    private static void WritePrivate(string path, string text)
    {
        var options = new FileStreamOptions
        {
            Mode = FileMode.Create,
            Access = FileAccess.Write,
            Share = FileShare.None,
        };
        if (!OperatingSystem.IsWindows())
        {
            options.UnixCreateMode = OwnerOnly;
        }

        using (var stream = new FileStream(path, options))
        using (var writer = new StreamWriter(stream, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false)))
        {
            writer.Write(text);
        }

        // An existing file keeps its old mode when it is truncated, so the mode is set again on Unix.
        if (!OperatingSystem.IsWindows())
        {
            File.SetUnixFileMode(path, OwnerOnly);
        }
    }

    /// <summary>
    /// Writes the accounts that hold a generated password to <paramref name="path"/>. Writes nothing when no account has a
    /// password, so an existing file keeps the passwords it already has. The file is written next to the target and moved
    /// into place, so a failed write never leaves a half-written file. Returns whether the file was written.
    /// </summary>
    public static bool WriteIfCreated(string path, IReadOnlyList<DemoAccount> accounts)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(path);
        ArgumentNullException.ThrowIfNull(accounts);

        var withPassword = accounts.Where(account => account.Password is not null).ToArray();
        if (withPassword.Length == 0)
        {
            return false;
        }

        var builder = new StringBuilder();
        builder.AppendLine("Parley demo accounts. Generated by seed-demo. Private: do not commit or share.");
        builder.AppendLine($"Organization: {SeedDemoOrganization.Name}");
        builder.AppendLine();
        builder.AppendLine("Email\tRole\tTeam\tPassword");
        foreach (var account in withPassword)
        {
            builder.Append(account.Email).Append('\t')
                .Append(account.RoleCode).Append('\t')
                .Append(account.TeamName ?? NoTeam).Append('\t')
                .AppendLine(account.Password);
        }

        EnsureDirectory(path);
        var temporary = path + TemporarySuffix;
        WritePrivate(temporary, builder.ToString());
        File.Move(temporary, path, overwrite: true);
        return true;
    }
}
